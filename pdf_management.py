from google.colab import files
from pypdf import PdfReader, PdfWriter
from pathlib import Path
from getpass import getpass

def unlock_pdf_colab():
    print("📂 Upload a PDF file")
    uploaded = files.upload()

    if not uploaded:
        print("❌ No file uploaded.")
        return

    input_pdf = next(iter(uploaded.keys()))
    input_path = Path(input_pdf)
    output_pdf = input_path.with_name(f"{input_path.stem}_unlocked.pdf")

    print(f"\n✅ Uploaded: {input_pdf}")

    password = getpass("🔐 Enter PDF password: ")

    try:
        reader = PdfReader(input_pdf)

        if not reader.is_encrypted:
            print("ℹ️ This PDF is not encrypted. Creating a plain copy anyway...")
        else:
            result = reader.decrypt(password)

            # In pypdf, decrypt() returns a truthy value when successful
            if not result:
                print("❌ Incorrect password or unsupported encryption.")
                return

            print("✅ PDF decrypted successfully.")

        writer = PdfWriter()

        total_pages = len(reader.pages)
        print(f"📄 Copying {total_pages} page(s)...")

        for i, page in enumerate(reader.pages, start=1):
            writer.add_page(page)
            if i % 10 == 0 or i == total_pages:
                print(f"   Processed {i}/{total_pages} pages")

        with open(output_pdf, "wb") as f:
            writer.write(f)

        print(f"\n🎉 Done! Saved as: {output_pdf}")
        files.download(str(output_pdf))

    except Exception as e:
        print(f"❌ Failed: {type(e).__name__}: {e}")

unlock_pdf_colab()

